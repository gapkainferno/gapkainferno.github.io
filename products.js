// РОЗУМНА ГЕНЕРАЦІЯ ВЕРСІЙ (АВТО-ЦІНА + РУЧНА НАЯВНІСТЬ)
// ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
(function() {
    if (typeof allProducts !== 'undefined') {
        Object.keys(allProducts).forEach(id => {
            const p = allProducts[id];

            if (p.category === 'seeds' && /\bSHU\b/i.test(p.heatLevel || '') && p.meta?.count) {
                p.meta.count = '8 насінин (+ бонус від ферми)';
            }
            
            if (p.category === 'seeds' || p.category === 'otherseeds') {
                
                // 1. Розрахунок ціни (завжди автоматично +25%)
                const isolatedPrice = Math.round(p.price * 1.25);
                
                p.seedVersions = {
                    openPollinated: {
                        label: "Open Pollinated",
                        price: p.price,
                        description: "Насіння вільного запилення.",
                        inStock: p.inStock
                    }
                };

                // Ізольовану версію додаємо тільки для тих товарів,
                // де ти явно вказала isolatedAvailable: true
                if (p.isolatedAvailable === true) {
                    p.seedVersions.isolated = {
                        label: "Ізольоване",
                        price: isolatedPrice,
                        description: "Контрольоване запилення.",
                        inStock: p.inStock
                    };
                }
            }
        });
        console.log("🔥 Gapka Homestead Inferno: Протоколи ціноутворення синхронізовано.");

        // ───────────────────────────────────────────────────────────────
        // АВТОМАТИЧНА СИНХРОНІЗАЦІЯ SEO-РОЗМІТКИ (JSON-LD)
        // ───────────────────────────────────────────────────────────────
        const syncSchemaWithDatabase = () => {
            const schemaScript = document.querySelector('script[type="application/ld+json"]');
            if (!schemaScript) return;

            try {
                const data = JSON.parse(schemaScript.textContent);
                const graph = data['@graph'] || [data];
                let wasUpdated = false;

                graph.forEach(obj => {
                    if (obj['@type'] === 'Product') {
                        const nameLower = obj.name.toLowerCase();
                        let targetCategory = "";

                        // Визначаємо категорію для агрегованих цін на головній
                        if (nameLower.includes("соуси")) targetCategory = "sauces";
                        else if (nameLower.includes("суперхотів")) targetCategory = "seeds";
                        else if (nameLower.includes("інше насіння")) targetCategory = "otherseeds";
                        else if (nameLower.includes("врожай пекла")) targetCategory = "fresh-peppers";

                        if (targetCategory) {
                            const allPrices = [];
                            let categoryInStock = false;
                            Object.values(allProducts)
                                .filter(p => p.category === targetCategory)
                                .forEach(p => {
                                    if (Number(p.price) > 0) {
                                        allPrices.push(Number(p.price));
                                    }
                                    if (p.inStock !== false) categoryInStock = true;
                                    if (p.isolatedAvailable) allPrices.push(Math.round(p.price * 1.25));
                                });

                            if (allPrices.length > 0 && obj.offers && obj.offers['@type'] === 'AggregateOffer') {
                                obj.offers.lowPrice = Math.min(...allPrices);
                                obj.offers.highPrice = Math.max(...allPrices);
                                obj.offers.offerCount = allPrices.length;
                                // Оновлюємо статус наявності
                                obj.offers.availability = categoryInStock 
                                    ? "https://schema.org/InStock" 
                                    : "https://schema.org/OutOfStock";
                                wasUpdated = true;
                            }
                        }
                    }
                });

                if (wasUpdated) {
                    schemaScript.textContent = JSON.stringify(data, null, 2);
                    console.log("✅ SEO: Ціни в JSON-LD синхронізовано з базою товарів.");
                }
            } catch (e) {
                console.warn("⚠️ SEO: Не вдалося автоматично оновити ціни в розмітці:", e);
            }
        };

        // Запускаємо синхронізацію після завантаження сторінки
        if (document.readyState === 'loading') {
            document.addEventListener('DOMContentLoaded', syncSchemaWithDatabase);
        } else {
            syncSchemaWithDatabase();
        }
    }
})();
